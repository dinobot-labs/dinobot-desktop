import { chromium } from "playwright-core";
import { createServer } from "vite";
import { resolve, join } from "node:path";
import { tmpdir } from "node:os";
import { mkdir } from "node:fs/promises";
import { strict as assert } from "node:assert";

const root = resolve(import.meta.dir, "..");
const output = process.env.NUDGE_QA_DIR ?? join(tmpdir(), "dinobot-nudge-qa");
await mkdir(output, {recursive:true});
const server = await createServer({root, configFile:join(root,"vite.config.ts"), server:{host:"127.0.0.1",port:0,strictPort:false}});
await server.listen();
const browser = await chromium.launch({channel:"chrome",headless:true});
try {
 const page = await browser.newPage({viewport:{width:1000,height:800},locale:"ko-KR"});
 const errors: string[] = [];
 page.on("pageerror", error => errors.push(error.message));
 await page.goto(server.resolvedUrls!.local[0]! + "test/browser/nudge.fixture.html");
 const rows = page.locator('[data-role="nudge"]');
 await rows.first().waitFor();
 assert.equal(await rows.count(),2);
 assert.equal(await page.locator('[data-index="2"]').getByText("dinobot", {exact:true}).count(),1);
 const button = rows.first().getByRole("button", {name:"내부 알림 보기"});
 assert.equal(await button.getAttribute("aria-expanded"),"false");
 const id = await button.getAttribute("aria-controls");
 const details = page.locator('[id="' + id + '"]');
 assert.equal(await details.isVisible(),false);
 assert.notEqual(id, await rows.nth(1).getByRole("button").getAttribute("aria-controls"));
 await page.screenshot({path:join(output,"light-collapsed.png"),fullPage:true});
 await button.focus(); await page.keyboard.press("Enter");
 assert.equal(await rows.first().getByRole("button").getAttribute("aria-expanded"),"true");
 assert.equal(await details.isVisible(),true);
 await page.waitForFunction(() => { const a=document.querySelector('[data-index="1"]')!.getBoundingClientRect(); const b=document.querySelector('[data-index="2"]')!.getBoundingClientRect(); return b.top >= a.bottom - 1; });
 assert.equal(await details.textContent(),'<from host="subagents"/>\nBackground work changed state after your last answer:\nSynthetic task completed; another is blocked.\n<script>window.untrusted = true</script>');
 assert.equal(await page.evaluate(() => "untrusted" in window),false);
 assert.equal(await rows.nth(1).getByRole("button").getAttribute("aria-expanded"),"false");
 await page.screenshot({path:join(output,"light-expanded.png"),fullPage:true});
 await page.keyboard.press("Space");
 assert.equal(await details.isVisible(),false);
 await page.setViewportSize({width:375,height:812});
 await page.evaluate(() => document.documentElement.classList.add("dark"));
 await rows.first().getByRole("button").click();
 assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true);
 assert.equal(await rows.first().evaluate(el => el.scrollWidth <= el.clientWidth),true);
 await page.screenshot({path:join(output,"dark-narrow-expanded.png"),fullPage:true});
 assert.equal(await page.locator('[data-role="user"]').count(),2);
 await page.setViewportSize({width:375,height:400});
 await page.keyboard.press("Control+Home");
 await page.waitForFunction(() => document.querySelector('[data-testid="transcript"]')!.scrollTop < 30);
 await page.keyboard.press("Control+ArrowDown");
 await page.waitForFunction(() => document.querySelector('[data-testid="transcript"]')!.scrollTop > 0);
 // Jumping to the last human prompt reaches the bottom (no pin there).
 await page.getByTestId("transcript").hover();
 await page.mouse.wheel(0,-120);
 const pin = page.getByTestId("pinned-prompt");
 await pin.waitFor();
 assert.equal(await pin.innerText(),"작업 상태를 확인해 줘");
 await page.keyboard.press("Control+f");
 await page.getByRole("textbox",{name:"이 대화에서 찾기"}).fill("Second wake");
 await page.getByTestId("find-bar").getByText("1/1",{exact:true}).waitFor();
 const secondButton = rows.nth(1).getByRole("button");
 const secondDetails = page.locator('[id="' + await secondButton.getAttribute("aria-controls") + '"]');
 assert.equal(await secondDetails.isVisible(),true,"active search hit reveals raw nudge details");
 assert.equal(await secondButton.getAttribute("aria-expanded"),"true");
 await page.keyboard.press("Escape");
 assert.equal(await secondDetails.isVisible(),false,"search-only disclosure closes when search ends");
 assert.equal(await details.isVisible(),true,"existing manual expansion survives search");
 await rows.first().getByRole("button").click();
 await page.keyboard.press("Control+f");
 const findInput = page.getByRole("textbox",{name:"이 대화에서 찾기"});
 await findInput.fill("Synthetic task completed");
 await page.getByTestId("find-bar").getByText("1/3",{exact:true}).waitFor();
 assert.equal(await details.isVisible(),true);
 assert.equal(await secondDetails.isVisible(),false,"inactive match stays collapsed");
 await findInput.press("Enter");
 await page.getByTestId("find-bar").getByText("2/3",{exact:true}).waitFor();
 assert.equal(await details.isVisible(),false,"previous active hit closes");
 assert.equal(await secondDetails.isVisible(),true);
 await secondButton.focus();
 await page.keyboard.press("Enter");
 assert.equal(await secondDetails.isVisible(),false,"manual close overrides search reveal");
 await page.keyboard.press("Space");
 assert.equal(await secondDetails.isVisible(),true,"manual reopen remains keyboard accessible");
 await findInput.press("Escape");
 assert.equal(await secondDetails.isVisible(),true,"explicit manual open survives search end");
 await secondButton.click();
 await page.keyboard.press("Control+f");
 await findInput.fill("Second wake");
 assert.equal(await secondDetails.isVisible(),true);
 await findInput.fill("");
 assert.equal(await secondDetails.isVisible(),false,"clearing query ends temporary reveal");
 await findInput.press("Escape");
 await page.screenshot({path:join(output,"transcript-search-navigation.png"),fullPage:true});
 const english = await browser.newPage();
 english.on("pageerror", error => errors.push(error.message));
 await english.addInitScript(() => { (window as unknown as {__dnLanguage: string}).__dnLanguage = "en"; });
 await english.goto(server.resolvedUrls!.local[0]! + "test/browser/nudge.fixture.html");
 const englishRow = english.locator('[data-role="nudge"]').first();
 await englishRow.getByRole("button",{name:"Show internal notification"}).waitFor();
 assert.equal(await englishRow.getAttribute("aria-label"),"Automatic notification");
 assert.equal(await englishRow.getByText("An automatic notification to continue the work",{exact:true}).isVisible(),true);
 await englishRow.getByRole("button",{name:"Show internal notification"}).click();
 assert.equal(await englishRow.getByRole("button",{name:"Hide internal notification"}).isVisible(),true);
 await english.close();
 assert.deepEqual(errors,[]);
 console.log("PASS: full Transcript + reducer/session fixture: next assistant header, disclosure remeasurement, keyboard/independent state, escaped raw readback, human prompt navigation/pin, raw search, 375px overflow, no page errors. Screenshots: " + output);
} finally { await browser.close(); await server.close(); }
